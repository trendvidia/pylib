"""Rebuild the static CPython this module links, for every target.

python-build-standalone's full archives ship CPython's object files and a
PYTHON.json saying how to link them. The objects are LLVM bitcode (its
pgo+lto builds), which a linker older than the LLVM that wrote them cannot
read, so each is compiled here to a native object, for the archive's own
target, with an LLVM at least as new. The objects are taken from
PYTHON.json, not from libpython's archive, whose member names repeat.

Every extension module CPython's own inittab names is included; the ones
it builds as shared libraries (_tkinter and the test modules) are not.

Each link_*.go names the clang that compiled its target's objects. A
rebuild with that clang reproduces deps/ byte for byte; another version
changes some objects' code. So a run with any other clang stops before
it changes anything, unless NEW_CLANG=1 says the compiler change is
meant (#13).

Usage: scripts/build.py            all targets
       scripts/build.py TRIPLE...  some
       NEW_CLANG=1 scripts/build.py  with a clang other than deps/'s
Needs: gh, zstd, and LLVM >= the bitcode's (LLVM env var, default
Homebrew's /opt/homebrew/opt/llvm/bin).
"""
import concurrent.futures as cf
import gzip
import json
import os
import re
import shutil
import subprocess
import sys
import tarfile

RELEASE = "20261003"
VERSION = "3.14.8"
TARGETS = {
    "aarch64-apple-darwin": "darwin_arm64",
    "x86_64-apple-darwin": "darwin_amd64",
    "aarch64-unknown-linux-gnu": "linux_arm64",
    "x86_64-unknown-linux-gnu": "linux_amd64",
}
# Left out of the payload: tests, GUI and IDE modules, what pip installs,
# and the build's own config. Compiled bytecode is rebuilt on demand.
STDLIB_SKIP = {"test", "idlelib", "tkinter", "turtledemo", "ensurepip", "site-packages", "lib-dynload", "__pycache__"}

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.environ.get("CACHE", os.path.expanduser("~/.cache/pylib"))
LLVM = os.environ.get("LLVM", "/opt/homebrew/opt/llvm/bin")
# Notices for linked code the archive's licenses/ lacks, copied next to them.
EXTRA_LICENSES = os.path.join(ROOT, "scripts", "licenses")
# License paths PYTHON.json names that do not match what is linked.
STALE_LICENSES = {
    # zlib and binascii: the archive's libz.a is zlib 1.3.2 (deflate's
    # banner says so), under LICENSE.zlib.txt; on darwin, -lz is the system's.
    "licenses/LICENSE.zlib-ng.txt",
}


def run(*args, **kw):
    return subprocess.run(args, check=True, **kw)


def clang_version():
    """The first line of clang --version, such as "Homebrew clang version 23.1.6"."""
    out = run(f"{LLVM}/clang", "--version", capture_output=True, text=True).stdout
    return out.splitlines()[0].strip()


def recorded_clang(plat):
    """The clang link_<plat>.go says compiled deps/<plat>, or None if no file."""
    path = os.path.join(ROOT, f"link_{plat}.go")
    if not os.path.exists(path):
        return None
    m = re.search(r"^// Code generated by scripts/build\.py .* with (.+); DO NOT EDIT\.$", open(path).read(), re.M)
    return m.group(1) if m else ""


def check_clang(triples):
    """Exits, before anything is built, if clang is not the one deps/ names."""
    if os.environ.get("NEW_CLANG") == "1":
        return
    have = clang_version()
    for t in triples:
        plat = TARGETS[t]
        want = recorded_clang(plat)
        if want is not None and want != have:
            was = want or f"a clang link_{plat}.go does not name"
            sys.exit(f"{t}: deps/{plat} was compiled by {was}, and {LLVM}/clang is {have}. "
                     "Point LLVM at that one, or set NEW_CLANG=1 to rebuild deps/ with this one.")


def fetch(triple):
    d = os.path.join(CACHE, f"{VERSION}-{RELEASE}-{triple}")
    if not os.path.exists(os.path.join(d, "python", "PYTHON.json")):
        os.makedirs(d, exist_ok=True)
        name = f"cpython-{VERSION}+{RELEASE}-{triple}-pgo+lto-full.tar.zst"
        run("gh", "release", "download", RELEASE, "-R", "astral-sh/python-build-standalone", "-p", name, "-D", d, "--clobber")
        run("sh", "-c", f'cd "{d}" && zstd -dc "{name}" | tar -x && rm "{name}"')
    return os.path.join(d, "python")


def native(src, dst, triple):
    """Compiles a bitcode object to a native one, or copies a native one."""
    kind = subprocess.run(["file", "-b", src], capture_output=True, text=True).stdout
    if "bitcode" not in kind:
        shutil.copy(src, dst)
        return
    target = triple.replace("apple-darwin", "apple-macosx")
    run(f"{LLVM}/clang", "-target", target, "-c", "-O2", "-fPIC", "-g0", "-Wno-override-module", "-x", "ir", src, "-o", dst,
        capture_output=True)


def build(triple):
    plat = TARGETS[triple]
    py = fetch(triple)
    info = json.load(open(os.path.join(py, "PYTHON.json")))
    b = info["build_info"]
    inittab = open(os.path.join(py, "build", "Modules", "config.c")).read()
    objs, links, licenses = list(b["core"]["objs"]) + [b["inittab_object"]], [], [info["license_path"]]
    for name, variants in sorted(b["extensions"].items()):
        e = variants[0]
        if not e.get("in_core") and e["init_fn"] not in inittab:
            continue
        licenses += e.get("license_paths") or []
        if e.get("in_core"):
            continue  # its objects are among the core's
        objs += e.get("objs", [])
        links += [l for l in e.get("links", []) if l not in links]
    links += [l for l in b["core"]["links"] if l not in links]

    out = os.path.join(ROOT, "deps", plat)
    shutil.rmtree(out, ignore_errors=True)
    os.makedirs(out)
    work = os.path.join(CACHE, "objs-" + triple)
    shutil.rmtree(work, ignore_errors=True)
    os.makedirs(work)
    objs = sorted(set(objs))
    with cf.ThreadPoolExecutor(os.cpu_count()) as ex:
        list(ex.map(lambda o: native(os.path.join(py, o), os.path.join(work, o.replace("/", "__")), triple), objs))
    run(f"{LLVM}/llvm-ar", "rcs", os.path.join(out, "libpython.a"), *[os.path.join(work, o.replace("/", "__")) for o in objs])

    flags = ["${SRCDIR}/deps/%s/libpython.a" % plat]
    for l in links:
        if l.get("framework"):
            flags += ["-framework", l["name"]]
        elif l.get("path_static"):
            base = os.path.basename(l["path_static"])
            shutil.copy(os.path.join(py, l["path_static"]), os.path.join(out, base))
            flags.append("${SRCDIR}/deps/%s/%s" % (plat, base))
        else:
            flags.append("-l" + l["name"])
    if plat.startswith("linux_"):
        # GNU ld reads each archive once, left to right, and PYTHON.json's
        # order puts libncursesw before libedit and libcrypto before libssl,
        # which need them: a group is rescanned until nothing more
        # resolves. lld and Apple's ld search every archive anyway.
        flags = ["-Wl,--start-group"] + flags + ["-Wl,--end-group"]
    # clang -O2 runs LLVM's call-graph-profile pass over the PGO-weighted
    # bitcode, and on Mach-O it leaves the result in __LLVM,__cg_profile.
    # Go 1.26.11 and 1.27.4 refuse any __LLVM section in an archive that
    # #cgo LDFLAGS names, as LTO input. Apple's ld lays out the binary the
    # same without it. ELF keeps its copy, .llvm.call-graph-profile, which
    # Go allows.
    strip = ["--strip-debug"]
    if plat.startswith("darwin_"):
        strip.append("--remove-section=__LLVM,__cg_profile")
    for a in os.listdir(out):
        run(f"{LLVM}/llvm-strip", *strip, os.path.join(out, a))

    shutil.copytree(os.path.join(py, info["python_paths"]["include"]), os.path.join(out, "include"))
    stdlib = os.path.join(py, info["python_paths"]["stdlib"])
    # gzip's header carries a time and a name unless told not to; both are
    # zeroed so a rebuild of the same release is byte for byte the same.
    gz = gzip.GzipFile(os.path.join(out, "stdlib.tar.gz"), "wb", compresslevel=9, mtime=0)
    gz.name = ""
    with tarfile.open(fileobj=gz, mode="w") as t:
        for d, dirs, files in os.walk(stdlib):
            dirs[:] = sorted(x for x in dirs if x not in STDLIB_SKIP and not x.startswith("config-"))
            for f in sorted(files):
                p = os.path.join(d, f)
                ti = t.gettarinfo(p, os.path.relpath(p, stdlib))
                ti.mtime, ti.uid, ti.gid, ti.uname, ti.gname = 0, 0, 0, "", ""
                with open(p, "rb") as fh:
                    t.addfile(ti, fh)
    gz.close()
    # Only the licenses PYTHON.json names for what is linked: the archive's
    # licenses/ also covers what is not (Tcl/Tk, X11, Berkeley DB).
    lic = os.path.join(out, "licenses")
    os.makedirs(lic)
    for p in sorted(set(licenses) - STALE_LICENSES):
        if os.path.exists(os.path.join(py, p)):
            shutil.copy(os.path.join(py, p), lic)
    # The archive's licenses leave out some of what is linked: zstd, which
    # PYTHON.json names but the archive lacks, and the code CPython
    # incorporates (mimalloc, HACL*, ...), which its LICENSE does not list.
    for f in os.listdir(EXTRA_LICENSES):
        shutil.copy(os.path.join(EXTRA_LICENSES, f), lic)
    for p in sorted(set(licenses) - STALE_LICENSES):
        if not os.path.exists(os.path.join(out, p)):
            sys.exit(f"{triple}: {p} is named by PYTHON.json for a linked extension and is missing")

    goos, goarch = plat.split("_")
    with open(os.path.join(ROOT, f"link_{plat}.go"), "w") as f:
        f.write(f"""// SPDX-License-Identifier: MIT
// Copyright (c) 2026 TrendVidia, LLC.

// Code generated by scripts/build.py from python-build-standalone {RELEASE} ({triple}) with {clang_version()}; DO NOT EDIT.

package pylib

/*
#cgo CFLAGS: -I${{SRCDIR}}/deps/{plat}/include
#cgo LDFLAGS: {' '.join(flags)}
*/
import "C"

import _ "embed"

//go:embed deps/{plat}/stdlib.tar.gz
var stdlib []byte
""")
    print(triple, len(objs), "objects")


if __name__ == "__main__":
    triples = sys.argv[1:] or list(TARGETS)
    for t in triples:
        if t not in TARGETS:
            sys.exit(f"{t}: not a target; the targets are {', '.join(TARGETS)}")
    check_clang(triples)
    for t in triples:
        build(t)
